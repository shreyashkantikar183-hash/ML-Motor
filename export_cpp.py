"""
export_cpp.py
Minimal, dependency-free exporter that ports a trained sklearn
RandomForestClassifier to a C++ header in the same style as
Eloquent ML's micromlgen output (majority-vote over per-tree
if/else trees). Used because micromlgen isn't installable in
this offline environment.
"""

def _port_tree(tree, node_id, feature_names, indent):
    t = tree.tree_
    pad = "    " * indent
    if t.children_left[node_id] == t.children_right[node_id]:
        # leaf
        class_idx = int(t.value[node_id][0].argmax())
        return f"{pad}votes[{class_idx}] += 1;\n"

    feat_idx = t.feature[node_id]
    threshold = float(t.threshold[node_id])
    left = _port_tree(tree, t.children_left[node_id], feature_names, indent + 1)
    right = _port_tree(tree, t.children_right[node_id], feature_names, indent + 1)
    out = f"{pad}if (x[{feat_idx}] <= {threshold}) {{\n"
    out += left
    out += f"{pad}}}\n{pad}else {{\n"
    out += right
    out += f"{pad}}}\n"
    return out


def port_random_forest(model, feature_names, class_names):
    """
    model: fitted sklearn RandomForestClassifier
    feature_names: list[str] in the exact order the model expects
    class_names: list[str] such that class_names[i] is model.classes_[i]
    Returns: C++ header source (str)
    """
    n_classes = len(class_names)
    trees_code = []
    for i, estimator in enumerate(model.estimators_):
        body = _port_tree(estimator, 0, feature_names, indent=6)
        trees_code.append(f"                        // tree #{i + 1}\n" + body)

    trees_joined = "\n".join(trees_code)

    case_lines = "\n".join(
        f'                            case {i}:\n                            return "{name}";'
        for i, name in enumerate(class_names)
    )

    header = f"""#pragma once
#include <cstdarg>
// Auto-generated by export_cpp.py — do not edit by hand.
// Features (in order): {", ".join(feature_names)}
namespace Eloquent {{
    namespace ML {{
        namespace Port {{
            class RandomForest {{
                public:
                    /**
                    * Predict class for features vector
                    */
                    int predict(float *x) {{
                        uint8_t votes[{n_classes}] = {{ 0 }};
{trees_joined}
                        // return argmax of votes
                        uint8_t classIdx = 0;
                        float maxVotes = votes[0];

                        for (uint8_t i = 1; i < {n_classes}; i++) {{
                            if (votes[i] > maxVotes) {{
                                classIdx = i;
                                maxVotes = votes[i];
                            }}
                        }}

                        return classIdx;
                    }}

                    /**
                    * Predict readable class name
                    */
                    const char* predictLabel(float *x) {{
                        return idxToLabel(predict(x));
                    }}

                    /**
                    * Convert class idx to readable name
                    */
                    const char* idxToLabel(uint8_t classIdx) {{
                        switch (classIdx) {{
{case_lines}
                            default:
                            return "Unknown";
                        }}
                    }}

                protected:
            }};
        }}
    }}
}}
"""
    return header
